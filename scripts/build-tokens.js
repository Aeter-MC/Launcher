/**
 * build-tokens.js
 * design/tokens.json + design/themes/*.json (W3C Design Tokens, as exported by Figma / Tokens Studio)
 *   -> src/renderer/tokens.css   CSS custom properties; each theme is a :root[data-theme="…"] block
 *   -> src/renderer/themes.js    theme list with preview colors for the settings picker
 *   -> src/themes.json           the same list for the main process (window background before paint)
 *
 * Variable names are the token path joined with "-": color.log.info -> --color-log-info.
 * Usage: npm run tokens            (one-off)
 *        npm run tokens -- --watch (rebuild on every save in design/)
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const DESIGN = path.join(root, 'design');
const BASE = path.join(DESIGN, 'tokens.json');
const THEMES_DIR = path.join(DESIGN, 'themes');
const OUT_CSS = path.join(root, 'src', 'renderer', 'tokens.css');
const OUT_JS = path.join(root, 'src', 'renderer', 'themes.js');
const OUT_JSON = path.join(root, 'src', 'themes.json');

function cssValue(token, type) {
  const v = token.$value;
  if (typeof v === 'string' && /^\{.+\}$/.test(v)) {
    // alias: {color.accent} -> var(--color-accent)
    return `var(--${v.slice(1, -1).split('.').join('-')})`;
  }
  switch (type) {
    case 'fontFamily':
      return (Array.isArray(v) ? v : [v])
        .map(f => (/^[a-z-]+$/.test(f) ? f : `"${f}"`))
        .join(', ');
    case 'shadow': {
      const list = Array.isArray(v) ? v : [v];
      return list.map(s => `${s.inset ? 'inset ' : ''}${s.offsetX} ${s.offsetY} ${s.blur} ${s.spread || '0px'} ${s.color}`).join(', ');
    }
    case 'dimension':
      return typeof v === 'object' && v !== null ? `${v.value}${v.unit}` : String(v);
    default:
      return String(v);
  }
}

function collect(node, pathParts = [], inheritedType, out = []) {
  const type = node.$type || inheritedType;
  if (Object.prototype.hasOwnProperty.call(node, '$value')) {
    out.push({ name: `--${pathParts.join('-')}`, value: cssValue(node, type), description: node.$description });
    return out;
  }
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$') || typeof child !== 'object' || child === null) continue;
    collect(child, [...pathParts, key], type, out);
  }
  return out;
}

function block(selector, vars, extra = []) {
  const lines = [`${selector} {`, ...extra.map(e => `  ${e}`)];
  for (const v of vars) lines.push(`  ${v.name}: ${v.value};${v.description ? ` /* ${v.description} */` : ''}`);
  lines.push('}');
  return lines.join('\n');
}

function readThemes() {
  if (!fs.existsSync(THEMES_DIR)) return [];
  return fs.readdirSync(THEMES_DIR)
    .filter(f => f.endsWith('.json'))
    .map(f => {
      const json = JSON.parse(fs.readFileSync(path.join(THEMES_DIR, f), 'utf-8'));
      const meta = (json.$extensions && json.$extensions['mcl.theme']) || {};
      return {
        id: meta.id || path.basename(f, '.json'),
        name: meta.name || path.basename(f, '.json'),
        mode: meta.mode === 'light' ? 'light' : 'dark',
        order: meta.order ?? 99,
        vars: collect(json)
      };
    })
    .sort((a, b) => (a.mode === b.mode ? a.order - b.order : a.mode === 'dark' ? -1 : 1));
}

function build() {
  const base = collect(JSON.parse(fs.readFileSync(BASE, 'utf-8')));
  const themes = readThemes();

  const parts = [
    '/* Generated from design/tokens.json and design/themes/*.json by scripts/build-tokens.js — do not edit by hand. */',
    block(':root', base, ['color-scheme: dark;'])
  ];
  for (const t of themes) {
    parts.push(block(`:root[data-theme="${t.id}"]`, t.vars, [`color-scheme: ${t.mode};`]));
  }
  fs.writeFileSync(OUT_CSS, parts.join('\n\n') + '\n', 'utf-8');

  // Preview colors for the picker come from the theme itself, falling back to the base tokens
  const pick = (t, name) => (t.vars.find(v => v.name === name) || base.find(v => v.name === name) || {}).value;
  const list = themes.map(t => ({
    id: t.id,
    name: t.name,
    mode: t.mode,
    preview: {
      bg: pick(t, '--color-bg'),
      side: pick(t, '--color-bg-side'),
      surface: pick(t, '--color-surface'),
      line: pick(t, '--color-line'),
      text: pick(t, '--color-text'),
      muted: pick(t, '--color-text-3'),
      accent: pick(t, '--color-accent')
    }
  }));
  fs.writeFileSync(OUT_JS, `/* Generated by scripts/build-tokens.js — do not edit by hand. */\nwindow.MCL_THEMES = ${JSON.stringify(list, null, 2)};\n`, 'utf-8');
  fs.writeFileSync(OUT_JSON, JSON.stringify(list, null, 2) + '\n', 'utf-8');

  console.log(`tokens.css: ${base.length} variables, ${themes.length} themes`);
}

build();

if (process.argv.includes('--watch')) {
  let timer;
  fs.watch(DESIGN, { recursive: true }, (event, file) => {
    if (!file || !file.endsWith('.json')) return;
    clearTimeout(timer);
    timer = setTimeout(() => {
      try {
        build();
      } catch (e) {
        console.error(`${file}:`, e.message);
      }
    }, 100);
  });
  console.log('Watching design/…');
}
