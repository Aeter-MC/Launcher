/**
 * instances-manager.js
 * Manages isolated Minecraft instances (like Prism Launcher & Modrinth App).
 */
const fs = require('fs');
const path = require('path');
const os = require('os');
const crypto = require('crypto');
const { t } = require('./i18n/i18n');

const PRISM_INSTANCES_DIR = path.join(process.env.APPDATA || '', 'PrismLauncher', 'instances');
const PRISM_ICONS_DIR = path.join(process.env.APPDATA || '', 'PrismLauncher', 'icons');

// Custom build icon of a native instance, stored next to instance.json
const ICON_FILE = 'icon.png';
const ICON_MIME = { '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.gif': 'image/gif', '.webp': 'image/webp', '.svg': 'image/svg+xml', '.ico': 'image/x-icon', '.bmp': 'image/bmp' };

/** Image file as a data: URL (the renderer's CSP allows no file: images), or null. */
function iconDataUrl(file) {
  const mime = ICON_MIME[path.extname(file).toLowerCase()];
  if (!mime) return null;
  try {
    return `data:${mime};base64,${fs.readFileSync(file).toString('base64')}`;
  } catch (e) {
    return null;
  }
}

/** Prism keeps custom icons as <iconKey>.<ext> in its icons folder; built-in keys have no file. */
function prismIconFile(iconKey) {
  if (!iconKey || iconKey === 'default' || /[\\/]/.test(iconKey)) return null;
  try {
    const f = fs.readdirSync(PRISM_ICONS_DIR).find(n => path.parse(n).name === iconKey && ICON_MIME[path.extname(n).toLowerCase()]);
    return f ? path.join(PRISM_ICONS_DIR, f) : null;
  } catch (e) {
    return null;
  }
}

/** Sets key=value in the text of a Prism instance.cfg, adding the line when it's missing. */
function setCfgValue(cfg, key, value) {
  const re = new RegExp(`^${key}=.*$`, 'm');
  const line = `${key}=${value}`;
  if (re.test(cfg)) return cfg.replace(re, line);
  // Prism writes CRLF on Windows: keep the file's own line endings
  const eol = cfg.includes('\r\n') ? '\r\n' : '\n';
  return cfg.replace(/\s*$/, eol) + line + eol;
}

// Not worth copying when importing: regenerated by the game
const SKIP_ON_IMPORT = new Set(['logs', 'crash-reports', '.cache', 'debug']);

/** All files under dir: [{ full, rel, size, mtime, atime }], skipping top-level folders in `skip`. */
function collectFiles(dir, skip = new Set()) {
  const out = [];
  const walk = (current, rel) => {
    let entries;
    try {
      entries = fs.readdirSync(current, { withFileTypes: true });
    } catch (e) {
      return;
    }
    for (const e of entries) {
      if (!rel && skip.has(e.name)) continue;
      const full = path.join(current, e.name);
      const r = rel ? path.join(rel, e.name) : e.name;
      if (e.isDirectory()) walk(full, r);
      else if (e.isFile()) {
        try {
          const st = fs.statSync(full);
          out.push({ full, rel: r, size: st.size, mtime: st.mtime, atime: st.atime });
        } catch (err) {}
      }
    }
  };
  walk(dir, '');
  return out;
}

class InstancesManager {
  constructor(userDataDir, versionManager) {
    this.instancesDir = path.join(userDataDir, 'instances');
    this.versionManager = versionManager;
    this.includePrism = false; // "sync" mode: Prism Launcher instances are used in place
    this.ensureDir(this.instancesDir);
  }

  ensureDir(dir) {
    if (!fs.existsSync(dir)) {
      try {
        fs.mkdirSync(dir, { recursive: true });
      } catch (e) {}
    }
  }

  /**
   * Reads an instance from a directory.
   */
  readInstance(dirPath) {
    const configJson = path.join(dirPath, 'instance.json');
    const mmcPackJson = path.join(dirPath, 'mmc-pack.json');
    const instanceCfg = path.join(dirPath, 'instance.cfg');

    // 1. Native MCL Instance
    if (fs.existsSync(configJson)) {
      try {
        const data = JSON.parse(fs.readFileSync(configJson, 'utf-8'));
        const mcDir = path.join(dirPath, 'minecraft');
        const modsDir = fs.existsSync(mcDir) ? path.join(mcDir, 'mods') : path.join(dirPath, 'mods');

        let modCount = 0;
        if (fs.existsSync(modsDir)) {
          modCount = fs.readdirSync(modsDir).filter(f => f.endsWith('.jar')).length;
        }

        return {
          id: data.id || path.basename(dirPath),
          name: data.name || path.basename(dirPath),
          version: data.version || '1.21.1',
          loader: data.loader || 'vanilla',
          loaderVersion: data.loaderVersion || '',
          versionId: data.versionId || '',
          icon: data.icon || 'grass',
          iconBlock: data.iconBlock || null,
          iconImage: data.customIcon ? iconDataUrl(path.join(dirPath, ICON_FILE)) : null,
          path: dirPath,
          minecraftDir: fs.existsSync(mcDir) ? mcDir : dirPath,
          modsDir: modsDir,
          modCount: modCount,
          lastPlayed: data.lastPlayed || null,
          totalPlaytime: data.totalPlaytime || 0,
          importedFrom: data.importedFrom || null,
          isPrism: false
        };
      } catch (e) {
        console.error('Error reading instance.json:', e);
      }
    }

    // 2. Prism Launcher Instance
    if (fs.existsSync(mmcPackJson) || fs.existsSync(instanceCfg)) {
      let name = path.basename(dirPath);
      let version = '1.21.1';
      let loader = 'vanilla';
      let loaderVersion = '';
      let icon = 'default';
      let lastPlayed = null;
      let totalPlaytime = 0;

      if (fs.existsSync(instanceCfg)) {
        const cfgText = fs.readFileSync(instanceCfg, 'utf-8');
        const nameMatch = cfgText.match(/^name=(.*)$/m);
        if (nameMatch) name = nameMatch[1].trim();

        const iconMatch = cfgText.match(/^iconKey=(.*)$/m);
        if (iconMatch) icon = iconMatch[1].trim();

        const lastMatch = cfgText.match(/^lastLaunchTime=(\d+)$/m);
        if (lastMatch) lastPlayed = parseInt(lastMatch[1], 10) || null;

        const timeMatch = cfgText.match(/^totalTimePlayed=(\d+)$/m);
        if (timeMatch) totalPlaytime = parseInt(timeMatch[1], 10) || 0;
      }

      if (fs.existsSync(mmcPackJson)) {
        try {
          const pack = JSON.parse(fs.readFileSync(mmcPackJson, 'utf-8'));
          if (pack.components) {
            const mcComp = pack.components.find(c => c.uid === 'net.minecraft');
            if (mcComp) version = mcComp.version || mcComp.cachedVersion || version;

            const fabricComp = pack.components.find(c => c.uid === 'net.fabricmc.fabric-loader');
            if (fabricComp) {
              loader = 'fabric';
              loaderVersion = fabricComp.version || '';
            }

            const quiltComp = pack.components.find(c => c.uid === 'org.quiltmc.quilt-loader');
            if (quiltComp) {
              loader = 'quilt';
              loaderVersion = quiltComp.version || '';
            }

            const forgeComp = pack.components.find(c => c.uid === 'net.minecraftforge' || c.uid === 'net.neoforged');
            if (forgeComp) {
              loader = forgeComp.uid.includes('neoforged') ? 'neoforge' : 'forge';
              loaderVersion = forgeComp.version || '';
            }
          }
        } catch (e) {}
      }

      const mcDir = ['minecraft', '.minecraft'].map(d => path.join(dirPath, d)).find(d => fs.existsSync(d))
        || path.join(dirPath, 'minecraft');
      const modsDir = fs.existsSync(mcDir) ? path.join(mcDir, 'mods') : path.join(dirPath, 'mods');

      let modCount = 0;
      if (fs.existsSync(modsDir)) {
        modCount = fs.readdirSync(modsDir).filter(f => f.endsWith('.jar')).length;
      }

      return {
        id: 'prism-' + path.basename(dirPath),
        name: name,
        version: version,
        loader: loader,
        loaderVersion: loaderVersion,
        icon: icon,
        iconBlock: null,
        iconImage: (() => { const f = prismIconFile(icon); return f ? iconDataUrl(f) : null; })(),
        path: dirPath,
        minecraftDir: fs.existsSync(mcDir) ? mcDir : dirPath,
        modsDir: modsDir,
        modCount: modCount,
        lastPlayed: lastPlayed,
        totalPlaytime: totalPlaytime,
        isPrism: true
      };
    }

    return null;
  }

  /**
   * Lists all available instances.
   */
  listInstances() {
    const list = [];
    const seenPaths = new Set();

    // 1. MCL native instances
    if (fs.existsSync(this.instancesDir)) {
      try {
        const dirs = fs.readdirSync(this.instancesDir, { withFileTypes: true });
        for (const d of dirs) {
          if (d.isDirectory()) {
            const fullPath = path.join(this.instancesDir, d.name);
            const inst = this.readInstance(fullPath);
            if (inst) {
              list.push(inst);
              seenPaths.add(fullPath);
            }
          }
        }
      } catch (e) {}
    }

    // 2. Prism Launcher instances, used in place (only when the user opted in)
    if (this.includePrism && fs.existsSync(PRISM_INSTANCES_DIR)) {
      try {
        const prismDirs = fs.readdirSync(PRISM_INSTANCES_DIR, { withFileTypes: true });
        for (const d of prismDirs) {
          if (d.isDirectory()) {
            const fullPath = path.join(PRISM_INSTANCES_DIR, d.name);
            if (!seenPaths.has(fullPath)) {
              const inst = this.readInstance(fullPath);
              if (inst) {
                list.push(inst);
                seenPaths.add(fullPath);
              }
            }
          }
        }
      } catch (e) {}
    }

    // Most recently played first, then alphabetically
    list.sort((a, b) => (b.lastPlayed || 0) - (a.lastPlayed || 0) || a.name.localeCompare(b.name));
    return list;
  }

  /**
   * Number of Prism Launcher instances available for import.
   */
  countPrismInstances() {
    if (!fs.existsSync(PRISM_INSTANCES_DIR)) return 0;
    try {
      return fs.readdirSync(PRISM_INSTANCES_DIR, { withFileTypes: true })
        .filter(d => d.isDirectory() && this.readInstance(path.join(PRISM_INSTANCES_DIR, d.name)))
        .length;
    } catch (e) {
      return 0;
    }
  }

  /**
   * Prism Launcher instances that can be imported, with size and whether a copy already exists.
   */
  listPrismInstances() {
    if (!fs.existsSync(PRISM_INSTANCES_DIR)) return [];
    const imported = new Set(this.listInstances().filter(i => i.importedFrom).map(i => path.resolve(i.importedFrom)));
    const list = [];
    for (const d of fs.readdirSync(PRISM_INSTANCES_DIR, { withFileTypes: true })) {
      if (!d.isDirectory()) continue;
      const dirPath = path.join(PRISM_INSTANCES_DIR, d.name);
      const inst = this.readInstance(dirPath);
      if (!inst || !inst.isPrism) continue;
      const files = fs.existsSync(inst.minecraftDir) ? collectFiles(inst.minecraftDir) : [];
      list.push({
        key: d.name,
        name: inst.name,
        version: inst.version,
        loader: inst.loader,
        loaderVersion: inst.loaderVersion,
        modCount: inst.modCount,
        sizeBytes: files.reduce((sum, f) => sum + f.size, 0),
        alreadyImported: imported.has(path.resolve(dirPath))
      });
    }
    return list.sort((a, b) => a.name.localeCompare(b.name));
  }

  /**
   * Copies a Prism Launcher instance into MCL. The original is left untouched.
   * onProgress({ copiedBytes, totalBytes })
   */
  async importPrismInstance(key, onProgress) {
    const srcDir = path.join(PRISM_INSTANCES_DIR, key);
    if (path.dirname(srcDir) !== PRISM_INSTANCES_DIR) throw new Error(t('Некорректная сборка'));
    const src = this.readInstance(srcDir);
    if (!src || !src.isPrism) throw new Error(t('Сборка Prism Launcher не найдена'));

    const slug = (src.name.replace(/[^a-zA-Z0-9_-]/g, '').toLowerCase() || 'instance') + '_' + Date.now().toString(36);
    const destDir = path.join(this.instancesDir, slug);
    const destMc = path.join(destDir, 'minecraft');

    const files = fs.existsSync(src.minecraftDir) ? collectFiles(src.minecraftDir, SKIP_ON_IMPORT) : [];
    const totalBytes = files.reduce((sum, f) => sum + f.size, 0);
    let copiedBytes = 0;
    let lastReport = 0;

    try {
      for (const f of files) {
        const dest = path.join(destMc, f.rel);
        await fs.promises.mkdir(path.dirname(dest), { recursive: true });
        await fs.promises.copyFile(f.full, dest);
        // Keep timestamps: settings transfer compares options.txt modification times
        await fs.promises.utimes(dest, f.atime, f.mtime).catch(() => {});
        copiedBytes += f.size;
        if (onProgress && Date.now() - lastReport > 150) {
          lastReport = Date.now();
          onProgress({ copiedBytes, totalBytes });
        }
      }
      this.ensureDir(path.join(destMc, 'mods'));

      fs.writeFileSync(path.join(destDir, 'instance.json'), JSON.stringify({
        id: slug,
        name: src.name,
        version: src.version,
        loader: src.loader,
        loaderVersion: src.loaderVersion,
        icon: 'grass',
        created: Date.now(),
        lastPlayed: src.lastPlayed,
        totalPlaytime: src.totalPlaytime,
        importedFrom: srcDir
      }, null, 2), 'utf-8');
    } catch (e) {
      fs.rmSync(destDir, { recursive: true, force: true });
      throw new Error(t('Не удалось скопировать «{name}»: {error}', { name: src.name, error: e.message }));
    }

    if (onProgress) onProgress({ copiedBytes: totalBytes, totalBytes });
    return this.readInstance(destDir);
  }

  /**
   * Creates a new isolated Minecraft instance.
   */
  async createInstance(options) {
    const {
      name = 'New Instance',
      version = '1.21.1',
      loader = 'vanilla',
      loaderVersion = '',
      versionId = version, // loader profile in versions/, installed by the caller
      icon = 'grass'
    } = options;

    const safeSlug = (name.replace(/[^a-zA-Z0-9_-]/g, '').toLowerCase() || 'instance') + '_' + Date.now().toString(36);
    const instDir = path.join(this.instancesDir, safeSlug);
    const mcDir = path.join(instDir, 'minecraft');
    const modsDir = path.join(mcDir, 'mods');

    this.ensureDir(modsDir);
    this.ensureDir(path.join(mcDir, 'saves'));
    this.ensureDir(path.join(mcDir, 'resourcepacks'));
    this.ensureDir(path.join(mcDir, 'shaderpacks'));

    const instData = {
      id: safeSlug,
      name: name,
      version: version,
      versionId: versionId,
      loader: loader,
      loaderVersion: loaderVersion,
      icon: icon,
      created: Date.now(),
      lastPlayed: null,
      totalPlaytime: 0
    };

    fs.writeFileSync(path.join(instDir, 'instance.json'), JSON.stringify(instData, null, 2), 'utf-8');

    return this.readInstance(instDir);
  }

  /**
   * Copies/duplicates an existing instance.
   */
  copyInstance(instanceId, newName) {
    const instances = this.listInstances();
    const source = instances.find(i => i.id === instanceId);
    if (!source) throw new Error(t('Инстанс не найден'));

    const safeSlug = (newName.replace(/[^a-zA-Z0-9_-]/g, '').toLowerCase() || 'instance') + '_' + Date.now().toString(36);
    const destDir = path.join(this.instancesDir, safeSlug);

    fs.cpSync(source.path, destDir, { recursive: true });

    // Update instance.json if exists
    const configPath = path.join(destDir, 'instance.json');
    if (fs.existsSync(configPath)) {
      try {
        const d = JSON.parse(fs.readFileSync(configPath, 'utf-8'));
        d.id = safeSlug;
        d.name = newName;
        d.created = Date.now();
        d.totalPlaytime = 0;
        fs.writeFileSync(configPath, JSON.stringify(d, null, 2), 'utf-8');
      } catch (e) {}
    }

    return this.readInstance(destDir);
  }

  /**
   * Deletes an instance.
   */
  deleteInstance(instanceId) {
    const instances = this.listInstances();
    const target = instances.find(i => i.id === instanceId);
    if (!target) return false;
    if (target.isPrism) {
      throw new Error(t('Сборки Prism Launcher удаляются из самого Prism Launcher'));
    }

    if (fs.existsSync(target.path)) {
      fs.rmSync(target.path, { recursive: true, force: true });
      return true;
    }
    return false;
  }

  /**
   * Sets the build icon. choice: { block: '<block name>' } | { png: Buffer } | null (back to the automatic one).
   * Prism instances only take an image: it goes to Prism's icons folder so Prism shows it too.
   */
  setInstanceIcon(instanceId, choice) {
    const target = this.listInstances().find(i => i.id === instanceId);
    if (!target) throw new Error(t('Инстанс не найден'));

    if (target.isPrism) {
      if (choice && !choice.png) throw new Error(t('Для сборок Prism Launcher можно задать только свою картинку'));
      const cfgPath = path.join(target.path, 'instance.cfg');
      let cfg = fs.existsSync(cfgPath) ? fs.readFileSync(cfgPath, 'utf-8') : '[General]\n';
      const key = 'aetermc_' + path.basename(target.path).replace(/[^a-zA-Z0-9_-]/g, '_');
      const own = prismIconFile(key);
      if (own) fs.rmSync(own, { force: true });
      if (choice) {
        this.ensureDir(PRISM_ICONS_DIR);
        fs.writeFileSync(path.join(PRISM_ICONS_DIR, key + '.png'), choice.png);
      }
      cfg = setCfgValue(cfg, 'iconKey', choice ? key : 'default');
      fs.writeFileSync(cfgPath, cfg, 'utf-8');
      return this.readInstance(target.path);
    }

    const configPath = path.join(target.path, 'instance.json');
    const d = JSON.parse(fs.readFileSync(configPath, 'utf-8'));
    const iconPath = path.join(target.path, ICON_FILE);
    if (choice && choice.png) {
      fs.writeFileSync(iconPath, choice.png);
      d.customIcon = true;
      delete d.iconBlock;
    } else {
      fs.rmSync(iconPath, { force: true });
      delete d.customIcon;
      if (choice && choice.block) d.iconBlock = choice.block;
      else delete d.iconBlock;
    }
    fs.writeFileSync(configPath, JSON.stringify(d, null, 2), 'utf-8');
    return this.readInstance(target.path);
  }

  /**
   * Records the launch time as soon as the game has started, not when it closes:
   * otherwise a running build still shows its previous launch.
   */
  markLaunched(instanceId) {
    const target = this.listInstances().find(i => i.id === instanceId);
    if (!target) return;

    if (target.isPrism) {
      const cfgPath = path.join(target.path, 'instance.cfg');
      try {
        let cfg = fs.existsSync(cfgPath) ? fs.readFileSync(cfgPath, 'utf-8') : '[General]\n';
        cfg = setCfgValue(cfg, 'lastLaunchTime', Date.now());
        fs.writeFileSync(cfgPath, cfg, 'utf-8');
      } catch (e) {}
      return;
    }

    const configPath = path.join(target.path, 'instance.json');
    if (fs.existsSync(configPath)) {
      try {
        const d = JSON.parse(fs.readFileSync(configPath, 'utf-8'));
        d.lastPlayed = Date.now();
        fs.writeFileSync(configPath, JSON.stringify(d, null, 2), 'utf-8');
      } catch (e) {}
    }
  }

  /**
   * Updates playtime for an instance.
   */
  updatePlaytime(instanceId, seconds) {
    const instances = this.listInstances();
    const target = instances.find(i => i.id === instanceId);
    if (!target) return;

    // Prism instances keep it in instance.cfg, so Prism itself shows the same numbers
    if (target.isPrism) {
      const cfgPath = path.join(target.path, 'instance.cfg');
      try {
        let cfg = fs.existsSync(cfgPath) ? fs.readFileSync(cfgPath, 'utf-8') : '[General]\n';
        cfg = setCfgValue(cfg, 'totalTimePlayed', (target.totalPlaytime || 0) + seconds);
        cfg = setCfgValue(cfg, 'lastTimePlayed', seconds);
        fs.writeFileSync(cfgPath, cfg, 'utf-8');
      } catch (e) {}
      return;
    }

    const configPath = path.join(target.path, 'instance.json');
    if (fs.existsSync(configPath)) {
      try {
        const d = JSON.parse(fs.readFileSync(configPath, 'utf-8'));
        d.totalPlaytime = (d.totalPlaytime || 0) + seconds;
        fs.writeFileSync(configPath, JSON.stringify(d, null, 2), 'utf-8');
      } catch (e) {}
    }
  }

  /**
   * Lists mods inside an instance.
   */
  listInstanceMods(instanceId) {
    const instances = this.listInstances();
    const target = instances.find(i => i.id === instanceId);
    if (!target || !fs.existsSync(target.modsDir)) return [];

    const list = [];
    try {
      const files = fs.readdirSync(target.modsDir);
      for (const file of files) {
        const full = path.join(target.modsDir, file);
        const stat = fs.statSync(full);
        if (stat.isFile() && (file.endsWith('.jar') || file.endsWith('.jar.disabled') || file.endsWith('.disabled'))) {
          const isEnabled = file.endsWith('.jar');
          list.push({
            fileName: file,
            fullPath: full,
            enabled: isEnabled,
            sizeBytes: stat.size,
            sizeFormatted: `${(stat.size / (1024 * 1024)).toFixed(2)} MB`,
            name: file.replace('.disabled', '').replace('.jar', '')
          });
        }
      }
    } catch (e) {}

    return list;
  }

  /**
   * Toggles a mod in an instance.
   */
  toggleInstanceMod(instanceId, fileName, enable) {
    const instances = this.listInstances();
    const target = instances.find(i => i.id === instanceId);
    if (!target) throw new Error(t('Инстанс не найден'));

    const currPath = path.join(target.modsDir, fileName);
    if (!fs.existsSync(currPath)) throw new Error(t('Мод не найден'));

    let newName;
    if (enable) {
      newName = fileName.replace(/\.disabled$/, '');
      if (!newName.endsWith('.jar')) newName += '.jar';
    } else {
      newName = fileName.replace(/\.disabled$/, '') + '.disabled';
    }

    const newPath = path.join(target.modsDir, newName);
    fs.renameSync(currPath, newPath);
    return { oldName: fileName, newName, enabled: enable };
  }

  /**
   * Adds a mod to an instance.
   */
  addModToInstance(instanceId, sourceFilePath) {
    const instances = this.listInstances();
    const target = instances.find(i => i.id === instanceId);
    if (!target) throw new Error(t('Инстанс не найден'));

    this.ensureDir(target.modsDir);
    const dest = path.join(target.modsDir, path.basename(sourceFilePath));
    fs.copyFileSync(sourceFilePath, dest);
    return { fileName: path.basename(sourceFilePath), dest };
  }

  /**
   * Deletes a mod from an instance.
   */
  deleteInstanceMod(instanceId, fileName) {
    const instances = this.listInstances();
    const target = instances.find(i => i.id === instanceId);
    if (!target) return false;

    const p = path.join(target.modsDir, fileName);
    if (fs.existsSync(p)) {
      fs.unlinkSync(p);
      return true;
    }
    return false;
  }
}

module.exports = {
  InstancesManager
};
